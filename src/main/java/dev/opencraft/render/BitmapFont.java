  private static void add(char c, String s) {
    GLYPHS.put(c, Arrays.stream(s.split(" ")).mapToInt(n -> Integer.parseInt(n, 2)).toArray());
  }

  public static int width(String text, int scale) {
    return text.codePointCount(0, text.length()) * 6 * scale;
  }

  public static void draw(
      Canvas canvas, String text, float x, float y, int color, int scale, boolean shadow) {
    if (shadow)
      draw(canvas, text, x + scale, y + scale, 0xff000000 | (color & 0xfcfcfc) >> 2, scale, false);
    float start = x;
    for (int point : text.codePoints().toArray()) {
      if (point == '\n') {
        y += 9 * scale;
        x = start;
        continue;
      }
      char c =
          java.text.Normalizer.normalize(
                  new String(Character.toChars(point)), java.text.Normalizer.Form.NFD)
              .charAt(0);
      int[] rows = GLYPHS.getOrDefault(c, GLYPHS.get('?'));
      for (int row = 0; row < 7; row++)
        for (int col = 0; col < 5; col++)
          if ((rows[row] & (1 << (4 - col))) != 0)
            canvas.rect(x + col * scale, y + row * scale, scale, scale, color);
      x += 6 * scale;
    }
  }
